/**
 * Resolve where the DeepSeek Harness install lives, and write the one file that
 * points TypeScript at its packages.
 *
 * Why this exists: the legacy project hard-coded `link:../../../DSH/node_modules/...`
 * into every package.json. On any other machine those relative paths are simply
 * wrong, and the first thing a fresh checkout hits is a broken install. Platform
 * packages are peer dependencies — the host supplies them at runtime — so they
 * must never be vendored or linked from a path baked into a manifest.
 *
 * esbuild does not need them on disk at all: the host half marks every
 * `@deepseek-ai/*` external, and the client half resolves against the page's
 * frozen module table (see ./seed-modules.mjs). Only `tsc` needs the type
 * declarations, so only `tsc` gets this generated mapping.
 *
 * Client-only seed modules (`@deepseek-ai/dsh-client-ui-slots` and friends)
 * have no package to resolve at all — the page supplies them. Those are
 * declared once in `types/client-seed.d.ts` instead.
 *
 * Resolution order:
 *   1. $DSH_INSTALL_DIR                              (explicit override)
 *   2. the real path of the `dsh` binary's package
 *   3. the global npm root's @deepseek-ai/dsh
 */

import { execFileSync } from 'node:child_process'
import { existsSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const workspaceRoot = resolve(here, '..')

/** @returns {string} the `@deepseek-ai/dsh` package directory */
export function resolveDshInstall() {
  const candidates = []

  if (process.env.DSH_INSTALL_DIR) candidates.push(process.env.DSH_INSTALL_DIR)

  try {
    const which = execFileSync('which', ['dsh'], { encoding: 'utf8' }).trim()
    if (which) {
      const prefix = resolve(dirname(which), '..')
      candidates.push(join(prefix, 'lib', 'node_modules', '@deepseek-ai', 'dsh'))
    }
  } catch { /* dsh not on PATH; fall through to npm */ }

  try {
    const root = execFileSync('npm', ['root', '-g'], { encoding: 'utf8' }).trim()
    if (root) candidates.push(join(root, '@deepseek-ai', 'dsh'))
  } catch { /* no npm; nothing left to try */ }

  for (const candidate of candidates) {
    if (candidate && existsSync(join(candidate, 'package.json'))) return candidate
  }

  throw new Error(
    'Could not locate the @deepseek-ai/dsh install. Set DSH_INSTALL_DIR to its package directory.\n'
    + `Tried:\n${candidates.map((c) => `  - ${c}`).join('\n') || '  (nothing — no override, no dsh on PATH, no npm)'}`,
  )
}

/** Types-only tsconfig mapping; generated, gitignored, never hand-edited. */
export function writePlatformTsconfig() {
  const dsh = resolveDshInstall()
  const platformModules = join(dsh, 'node_modules', '@deepseek-ai')
  const out = join(workspaceRoot, 'tsconfig.platform.json')

  writeFileSync(out, `${JSON.stringify({
    // Generated by tools/resolve-platform.mjs — do not edit, do not commit.
    compilerOptions: {
      paths: {
        // Point at each package's declaration entry, not at the package
        // directory: under `moduleResolution: nodenext` a `paths` substitution
        // that lands on a directory is not resolved through that package's
        // `exports` map, and the lookup falls through to node_modules and
        // fails. A concrete `.d.ts` always resolves.
        '@deepseek-ai/*': [
          join(platformModules, '*', 'lib', 'types', 'index.d.ts'),
          join(platformModules, '*'),
        ],
      },
    },
  }, null, 2)}\n`)

  return { dsh, out }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { dsh, out } = writePlatformTsconfig()
  console.log(`dsh install : ${dsh}`)
  console.log(`tsconfig    : ${out}`)
}
